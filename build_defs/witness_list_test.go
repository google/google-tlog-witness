// Package witness_list_test validates a witness list generated by the
// concatenated_witness_list macro.
//
// A witness list contains only the "witness" and "group" lines of a
// tlog-policy, with no "log" or "quorum" lines. A consumer reads it by
// appending a "quorum none" line and parsing the result as a tlog-policy; this
// test checks that the list is accepted in the same way.
package witness_list_test

import (
	"flag"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/transparency-dev/formats/policy"
)

var witnessList = flag.String("witness_list", "", "Path to the witness list file.")

// runfile resolves a workspace-relative path, as produced by Bazel's
// $(rootpath), to something openable.
//
// Test runners differ in the working directory they use — some the root of
// the runfiles tree, some the directory of the package under test — so try
// the path as given before resolving it against the runfiles root.
func runfile(t *testing.T, path string) string {
	t.Helper()
	candidates := []string{path}
	if root := os.Getenv("TEST_SRCDIR"); root != "" {
		candidates = append(candidates,
			filepath.Join(root, os.Getenv("TEST_WORKSPACE"), path),
			filepath.Join(root, path))
	}
	for _, c := range candidates {
		if _, err := os.Stat(c); err == nil {
			return c
		}
	}
	t.Fatalf("cannot find %q; tried %v", path, candidates)
	return ""
}

// TestWitnessList checks that the witness list contains only "witness" and
// "group" lines, defines at least one witness, and parses as a tlog-policy
// with a "quorum none" line appended.
func TestWitnessList(t *testing.T) {
	if *witnessList == "" {
		t.Fatal("--witness_list must be set")
	}
	raw, err := os.ReadFile(runfile(t, *witnessList))
	if err != nil {
		t.Fatalf("reading %s: %v", *witnessList, err)
	}

	for i, line := range strings.Split(string(raw), "\n") {
		fields := strings.Fields(line)
		if len(fields) == 0 || strings.HasPrefix(fields[0], "#") {
			continue
		}
		if keyword := fields[0]; keyword != "witness" && keyword != "group" {
			t.Errorf("%s: line %d: a witness list holds only \"witness\" and \"group\" lines, got %q", *witnessList, i+1, line)
		}
	}

	var p policy.TLogPolicy
	if err := p.Unmarshal(append(raw, []byte("\nquorum none\n")...)); err != nil {
		t.Fatalf("%s does not parse as a tlog-policy with a quorum line added: %v", *witnessList, err)
	}
	if len(p.Witnesses) == 0 {
		t.Errorf("%s defines no witnesses", *witnessList)
	}
}
